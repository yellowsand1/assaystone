"""A comparable table of acceptance contracts.

A report card answers four questions for one contract. A leaderboard puts
several contracts side by side, so a reader can see the trade-off instead of a
single number: a short contract may have perfect recall and no coverage; a long
one may cover everything and still leak semantics. Both facts belong on the same
page.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from .contract import Contract
from .model import load_traces
from .reportcard import ReportCard, run_report_card


class LeaderboardError(ValueError):
    """The leaderboard manifest cannot be used."""


@dataclass
class Entry:
    name: str
    card: ReportCard

    @property
    def cost(self) -> float:
        if self.card.recall is not None:
            return self.card.recall.avg_cost
        return self.card.coverage.estimated_cost_usd

    def to_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "domain": self.card.domain,
            "ok": self.card.ok,
            "headline": self.card.headline,
            "cost_usd": round(self.cost, 8),
            "card": self.card.to_dict(),
        }


@dataclass
class Leaderboard:
    name: str
    entries: list[Entry] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return all(entry.card.ok for entry in self.entries)

    def to_dict(self) -> dict[str, Any]:
        return {
            "leaderboard": self.name,
            "ok": self.ok,
            "entries": [entry.to_dict() for entry in self.entries],
        }

    def to_markdown(self) -> str:
        lines: list[str] = []
        add = lines.append
        add(f"# Leaderboard: {self.name}")
        add("")
        add(
            "> Generated by `assaystone leaderboard`. Coverage is measured against "
            "the contract's declared defects; recall on its labelled traces; "
            "resistance on its domain's adversarial families."
        )
        add("")
        add(
            "| entry | domain | protocol | coverage | at risk | recall | escaped | "
            "resistance | false alarms | cost / run | result |"
        )
        add("|---|---|---|---|---|---|---|---|---|---|---|")
        for entry in self.entries:
            card = entry.card
            protocol = "ok" if card.protocol.ok else f"{len(card.protocol.violations)} violations"
            coverage = f"{card.coverage.independent_rate:.0%}"
            at_risk = str(len(card.coverage.at_risk))
            recall = (
                f"{card.recall.catch_rate:.0%}"
                if card.recall is not None
                else "—"
            )
            escaped = str(card.recall.escaped) if card.recall is not None else "—"
            false_alarms = (
                str(card.recall.false_alarms)
                if card.recall is not None
                else "—"
            )
            add(
                f"| `{entry.name}` | {card.domain or '—'} | {protocol} | "
                f"{coverage} | {at_risk} | {recall} | {escaped} | "
                f"{card.resistance.resistance:.0%} | {false_alarms} | "
                f"${entry.cost:.6f} | "
                f"{'PASS' if card.ok else 'NEEDS WORK'} |"
            )
        add("")
        add("## How to read this")
        add("")
        add(
            "- **Coverage** is the share of declared defect classes decided by an "
            "independent check. A 100% coverage with zero declared defects is not "
            "a result."
        )
        add(
            "- **Resistance** is scoped to the contract's domain. Mechanical and "
            "lineage attacks should be 100%; semantic attacks are expected to "
            "escape."
        )
        add(
            "- **Recall** is measured only on the labelled traces supplied to the "
            "entry. An entry without traces has no recall column."
        )
        add(
            "- **Cost / run** is the average verification cost per trace when "
            "recall is measured, otherwise the sum of declared check costs."
        )
        add("")
        return "\n".join(lines)


def run_leaderboard(manifest: str | Path) -> Leaderboard:
    path = Path(manifest)
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise LeaderboardError(f"manifest not found: {path}") from exc
    except json.JSONDecodeError as exc:
        raise LeaderboardError(f"invalid manifest JSON in {path}: {exc}") from exc
    if not isinstance(data, dict) or not isinstance(data.get("entries"), list):
        raise LeaderboardError(f"manifest has no entries: {path}")
    base = path.parent

    entries: list[Entry] = []
    for item in data["entries"]:
        if not isinstance(item, dict) or not item.get("contract"):
            raise LeaderboardError("each entry needs a contract")
        name = str(item.get("name") or item["contract"])
        try:
            contract = Contract.load(base / item["contract"])
        except (OSError, json.JSONDecodeError, KeyError, ValueError) as exc:
            raise LeaderboardError(
                f"{name}: cannot load contract {item['contract']}: {exc}"
            ) from exc
        traces = (
            load_traces(base / item["traces"]) if item.get("traces") else None
        )
        baseline = base / item.get("baseline", ".")
        goodhart_corpus = (
            base / item["goodhart_corpus"] if item.get("goodhart_corpus") else None
        )
        goodhart_thresholds = (
            base / item["goodhart_thresholds"]
            if item.get("goodhart_thresholds")
            else None
        )
        entries.append(
            Entry(
                name=name,
                card=run_report_card(
                    contract,
                    traces=traces,
                    baseline=baseline,
                    goodhart_corpus=goodhart_corpus,
                    goodhart_thresholds=goodhart_thresholds,
                ),
            )
        )
    return Leaderboard(name=str(data.get("name", path.stem)), entries=entries)


def render_summary(board: Leaderboard) -> str:
    lines = [
        f"Leaderboard: {board.name}",
        f"{'entry':<22} {'coverage':>9} {'recall':>7} {'resistance':>11} "
        f"{'cost/run':>10} result",
    ]
    for entry in board.entries:
        card = entry.card
        recall = f"{card.recall.catch_rate:.0%}" if card.recall is not None else "—"
        lines.append(
            f"{entry.name:<22} {card.coverage.independent_rate:>8.0%} "
            f"{recall:>7} {card.resistance.resistance:>10.0%} "
            f"${entry.cost:>9.6f} {'PASS' if card.ok else 'NEEDS WORK'}"
        )
    return "\n".join(lines)
